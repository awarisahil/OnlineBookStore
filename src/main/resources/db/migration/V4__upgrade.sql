CREATE TABLE reviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id        VARCHAR(100)  NOT NULL REFERENCES books (barcode),
    customer_email VARCHAR(200)  NOT NULL REFERENCES users (email),
    rating         INT           NOT NULL,
    text           VARCHAR(2000) NOT NULL,
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    hidden         BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT reviews_rating_ck CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT reviews_one_per_user UNIQUE (book_id, customer_email)
);

CREATE TABLE wishlist_items (
    customer_email VARCHAR(200) NOT NULL REFERENCES users (email),
    book_id        VARCHAR(100) NOT NULL REFERENCES books (barcode),
    added_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (customer_email, book_id)
);

CREATE TABLE promo_codes (
    code        VARCHAR(50)   PRIMARY KEY,
    percent_off INT           NOT NULL,
    min_order   NUMERIC(10,2) NOT NULL DEFAULT 0,
    max_uses    INT,
    used_count  INT           NOT NULL DEFAULT 0,
    expires_at  TIMESTAMP,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT promo_percent_ck CHECK (percent_off BETWEEN 1 AND 90)
);

CREATE TABLE stock_notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    VARCHAR(100) NOT NULL REFERENCES books (barcode),
    email      VARCHAR(200) NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notified   BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT stock_notifications_one_per_user UNIQUE (book_id, email)
);

CREATE TABLE contact_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)  NOT NULL,
    email      VARCHAR(200)  NOT NULL,
    subject    VARCHAR(200)  NOT NULL,
    message    VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_flag  BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       VARCHAR(200) NOT NULL,
    action_type VARCHAR(100) NOT NULL,
    detail      VARCHAR(500),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recently_viewed (
    customer_email VARCHAR(200) NOT NULL REFERENCES users (email),
    book_id        VARCHAR(100) NOT NULL REFERENCES books (barcode),
    viewed_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (customer_email, book_id)
);

